-- Create BUS_TRIPS table

CREATE TABLE BUS_TRIPS (
    TRIP_ID INTEGER PRIMARY KEY,
    BUS_ID INTEGER,
    ROUTE_ID INTEGER,
    TRIP_DATE TEXT,
    PASSENGER_COUNT INTEGER,
    FARE REAL,
    DELAY_MINUTES INTEGER
);

