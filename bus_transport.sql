-- SQL QUERY 1
-- Display bus trip records

SELECT BUS_ID,
       ROUTE_ID,
       TRIP_DATE,
       PASSENGER_COUNT,
       DELAY_MINUTES
FROM BUS_TRIPS;


-- SQL QUERY 2
-- Total passenger count for each route

SELECT ROUTE_ID,
       SUM(PASSENGER_COUNT) AS TOTAL_PASSENGERS
FROM BUS_TRIPS
GROUP BY ROUTE_ID;


-- SQL QUERY 3
-- Total fare revenue generated by each bus

SELECT BUS_ID,
       SUM(PASSENGER_COUNT * FARE) AS TOTAL_REVENUE
FROM BUS_TRIPS
GROUP BY BUS_ID;


-- SQL QUERY 4
-- Trips delayed by more than 15 minutes

SELECT TRIP_ID,
       BUS_ID,
       ROUTE_ID,
       TRIP_DATE,
       DELAY_MINUTES
FROM BUS_TRIPS
WHERE DELAY_MINUTES > 15;


-- SQL QUERY 5
-- Average passengers per trip for each route

SELECT ROUTE_ID,
       AVG(PASSENGER_COUNT) AS AVERAGE_PASSENGERS
FROM BUS_TRIPS
GROUP BY ROUTE_ID;


-- PL/SQL TASK 1
-- SQLite equivalent: Calculate trip revenue

SELECT TRIP_ID,
       PASSENGER_COUNT,
       FARE,
       PASSENGER_COUNT * FARE AS TRIP_REVENUE
FROM BUS_TRIPS;


-- PL/SQL TASK 2
-- SQLite equivalent: Update passenger count

UPDATE BUS_TRIPS
SET PASSENGER_COUNT = 50
WHERE TRIP_ID = 1;


-- PL/SQL TASK 3
-- SQLite equivalent: Route-wise passenger and delay report

SELECT ROUTE_ID,
       SUM(PASSENGER_COUNT) AS TOTAL_PASSENGERS,
       AVG(DELAY_MINUTES) AS AVERAGE_DELAY
FROM BUS_TRIPS
GROUP BY ROUTE_ID;